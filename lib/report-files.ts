import Papa from "papaparse";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { GeneratedReport, ReportFormat } from "@/lib/reports";

const navy = [10, 15, 31] as const;
const gold = [212, 175, 55] as const;
const ivory = [245, 241, 232] as const;

function formatPeriod(report: GeneratedReport) {
  return `${report.period.startDate} — ${report.period.endDate}`;
}

function createPdf(report: GeneratedReport) {
  const document = new jsPDF({ unit: "mm", format: "a4" });
  const pageWidth = document.internal.pageSize.getWidth();
  const pageHeight = document.internal.pageSize.getHeight();

  document.setFillColor(...navy);
  document.rect(0, 0, pageWidth, pageHeight, "F");
  document.setDrawColor(...gold);
  document.setLineWidth(0.35);
  document.rect(12, 12, pageWidth - 24, pageHeight - 24);
  document.setFillColor(...gold);
  document.circle(pageWidth - 38, 42, 18, "F");
  document.setFillColor(...navy);
  document.circle(pageWidth - 38, 42, 17.4, "F");

  document.setTextColor(...gold);
  document.setFont("times", "bold");
  document.setFontSize(11);
  document.text("GMAILREPORTER  /  PRIVATE INTELLIGENCE", 25, 34);
  document.setDrawColor(...gold);
  document.line(25, 42, 70, 42);

  document.setTextColor(...ivory);
  document.setFont("times", "bold");
  document.setFontSize(34);
  document.text("Email Intelligence", 25, 91);
  document.setFontSize(23);
  document.text("Annual Report", 25, 104);
  document.setTextColor(205, 200, 187);
  document.setFont("helvetica", "normal");
  document.setFontSize(11);
  document.text("A considered view of your communication landscape.", 25, 116);

  document.setDrawColor(85, 75, 48);
  document.line(25, 143, pageWidth - 25, 143);
  document.setTextColor(...gold);
  document.setFont("helvetica", "bold");
  document.setFontSize(8);
  document.text("REPORTING PERIOD", 25, 157);
  document.text("PREPARED", 25, 176);
  document.setTextColor(...ivory);
  document.setFont("helvetica", "normal");
  document.setFontSize(13);
  document.text(formatPeriod(report), 25, 165);
  document.text(
    new Intl.DateTimeFormat("en-US", {
      dateStyle: "long",
      timeZone: "UTC",
    }).format(new Date(report.createdAt)),
    25,
    184,
  );
  document.setTextColor(155, 151, 139);
  document.setFontSize(8);
  document.text("CONFIDENTIAL  ·  GENERATED BY GMAILREPORTER", 25, pageHeight - 29);
  document.text("01", pageWidth - 34, pageHeight - 29);

  document.addPage();
  document.setFillColor(...navy);
  document.rect(0, 0, pageWidth, pageHeight, "F");
  document.setTextColor(...gold);
  document.setFont("helvetica", "bold");
  document.setFontSize(9);
  document.text("GMAILREPORTER  /  EXECUTIVE SUMMARY", 17, 18);
  document.setTextColor(...ivory);
  document.setFont("times", "bold");
  document.setFontSize(25);
  document.text("Your inbox, in perspective.", 17, 32);
  document.setTextColor(185, 183, 174);
  document.setFont("helvetica", "normal");
  document.setFontSize(9);
  document.text(`${formatPeriod(report)}  ·  ${report.summary.total} messages reviewed`, 17, 40);

  autoTable(document, {
    startY: 51,
    head: [["KEY METRIC", "VALUE"]],
    body: [
      ["Total emails", String(report.summary.total)],
      ["Unread", String(report.summary.unread)],
      ["Starred", String(report.summary.starred)],
      ["Important", String(report.summary.important)],
    ],
    theme: "grid",
    headStyles: { fillColor: [...gold], textColor: [...navy], fontStyle: "bold" },
    bodyStyles: { fillColor: [17, 26, 46], textColor: [...ivory], lineColor: [45, 54, 72] },
    alternateRowStyles: { fillColor: [20, 29, 47] },
    styles: { font: "helvetica", fontSize: 9, cellPadding: 3.5 },
    margin: { left: 17, right: 17 },
  });

  const summaryEndY =
    (document as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable
      ?.finalY ?? 51;
  autoTable(document, {
    startY: summaryEndY + 10,
    head: [["TOP SENDERS", "EMAIL", "MESSAGES"]],
    body: report.perSender.slice(0, 8).map((row) => [row.name, row.email, String(row.count)]),
    theme: "grid",
    headStyles: { fillColor: [37, 43, 58], textColor: [...gold], fontStyle: "bold" },
    bodyStyles: { fillColor: [17, 26, 46], textColor: [...ivory], lineColor: [45, 54, 72] },
    alternateRowStyles: { fillColor: [20, 29, 47] },
    styles: { font: "helvetica", fontSize: 8, cellPadding: 3, overflow: "linebreak" },
    columnStyles: { 1: { cellWidth: 75 }, 2: { cellWidth: 23, halign: "right" } },
    margin: { left: 17, right: 17 },
  });

  const finalY =
    (document as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable
      ?.finalY ?? summaryEndY;
  if (finalY < pageHeight - 47) {
    autoTable(document, {
      startY: finalY + 8,
      head: [["DATE", "EMAILS"]],
      body: report.perDay.slice(-10).map((row) => [row.date, String(row.count)]),
      theme: "grid",
      headStyles: { fillColor: [37, 43, 58], textColor: [...gold], fontStyle: "bold" },
      bodyStyles: { fillColor: [17, 26, 46], textColor: [...ivory], lineColor: [45, 54, 72] },
      alternateRowStyles: { fillColor: [20, 29, 47] },
      styles: { font: "helvetica", fontSize: 8, cellPadding: 2.5 },
      margin: { left: 17, right: 17 },
    });
  }

  const pageCount = document.getNumberOfPages();
  for (let page = 2; page <= pageCount; page += 1) {
    document.setPage(page);
    document.setDrawColor(55, 59, 68);
    document.line(17, pageHeight - 15, pageWidth - 17, pageHeight - 15);
    document.setTextColor(150, 150, 150);
    document.setFontSize(8);
    document.text("CONFIDENTIAL  ·  GMAILREPORTER", 17, pageHeight - 9);
    document.text(
      `${String(page).padStart(2, "0")} / ${String(pageCount).padStart(2, "0")}`,
      pageWidth - 17,
      pageHeight - 9,
      { align: "right" },
    );
  }

  return document.output("blob");
}

export function createReportFile(
  report: GeneratedReport,
  format: ReportFormat,
): Blob {
  if (format === "json") {
    return new Blob([JSON.stringify(report, null, 2)], {
      type: "application/json;charset=utf-8",
    });
  }

  if (format === "csv") {
    const rows = [
      { section: "summary", name: "Total emails", value: report.summary.total },
      { section: "summary", name: "Unread", value: report.summary.unread },
      { section: "summary", name: "Starred", value: report.summary.starred },
      { section: "summary", name: "Important", value: report.summary.important },
      ...report.perSender.map((row) => ({
        section: "sender",
        name: row.name,
        email: row.email,
        value: row.count,
      })),
      ...report.perDay.map((row) => ({
        section: "day",
        name: row.date,
        value: row.count,
      })),
      ...report.perLabel.map((row) => ({
        section: "label",
        name: row.name,
        value: row.count,
      })),
      ...report.topKeywords.map((row) => ({
        section: "subject keyword",
        name: row.keyword,
        value: row.count,
      })),
    ];

    return new Blob([`\uFEFF${Papa.unparse(rows)}`], {
      type: "text/csv;charset=utf-8",
    });
  }

  return createPdf(report);
}
